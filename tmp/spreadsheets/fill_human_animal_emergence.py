def profile_for_row(domain: str, name: str, sci: str) -> tuple[dict[str, str], str]:
    sci_key = norm(sci)
    name_key = norm(name)
    if domain == "human":
        if sci_key in SCIENCE_OVERRIDES:
            return SCIENCE_OVERRIDES[sci_key], f"science_override:{sci_key}"
        if name_key in HUMAN_NAME_PROFILES:
            return HUMAN_NAME_PROFILES[name_key], f"name_profile:{name_key}"
        return human_fallback(name_key, sci_key), f"fallback_human:{name_key}"
